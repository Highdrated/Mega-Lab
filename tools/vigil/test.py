        await pg.evaluate(f"SHIFT = {39 + n}; S.watch = null; ensureWatch(); S.watch.items.forEach(it => {{ if (it.k === 'oops') S.watch.done.push(it.id); if (it.k === 'lesson') S.read.push(it.g + it.l); if (it.k === 'trial') S.watch.trial = true; if (it.k === 'case') S.watch.case = true; }}); watchCheck()")
