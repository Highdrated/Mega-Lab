    await pg.fill("#wtin", R_.get("cmd") or R_["a"][0])
    await pg.press("#wtin", "Enter")
    check(await pg.evaluate(f"!S.miss.some(m => m.id === {sid!r}) && S.cleared === {cl + 1}"), "after the 7-day review a right answer clears it")

    await pg.evaluate("S.nights = []; S.unlocks = []; S.skin = 'paper'; SHIFT = 40; save()")
