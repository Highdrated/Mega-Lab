import asyncio, os, re, subprocess, sys
from playwright.async_api import async_playwright

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
subprocess.run(["node", os.path.join(HERE, "build.js")], check=True, stdout=subprocess.DEVNULL)
DEMO_F = "file://" + os.path.join(HERE, "out", "vigil-demo.html")
LAB_F = "file://" + os.path.join(ROOT, "labs", "vigil.html")
FAIL = []


def check(ok, msg):
    if not ok:
        FAIL.append(msg)
        print("FAIL", msg)


async def ps(pg, cmd):
    await pg.fill("#psin", cmd)
    await pg.press("#psin", "Enter")
    await pg.wait_for_timeout(40)


async def last_lines(pg, n=3):
    return (await pg.inner_text("#psw .psb")).strip().split("\n")[-n:]


def registry():
    cfg = open(os.path.join(ROOT, "js", "labs.config.js")).read()
    check('id: "vigil"' in cfg and 'path: "labs/vigil.html"' in cfg, "Vigil registered in js/labs.config.js")
    check(os.path.exists(os.path.join(ROOT, "labs", "vigil.html")), "labs/vigil.html built")
    st = open(os.path.join(ROOT, "js", "station.js")).read()
    check('["vigil", /^vigil\\.v1$/]' in st, "station tracks vigil.v1")
    sw = open(os.path.join(ROOT, "sw.js")).read()
    idx = open(os.path.join(ROOT, "index.html")).read()
    for f in ["labs.config.js", "station.js"]:
        a = re.search(re.escape(f) + r"\?v=(\d+)", sw)
        c = re.search(re.escape(f) + r"\?v=(\d+)", idx)
        check(a and c and a.group(1) == c.group(1), f"{f} version matches in sw.js and index.html")
    lab = open(os.path.join(ROOT, "labs", "vigil.html")).read()
    check("const DEMO = false;" in lab and 'DEMO ? "vigil.demo.v1" : "vigil.v1"' in lab, "lab build uses the vigil.v1 key")


async def fresh_lab(pg):
    check(await pg.evaluate("S.sl") == 0 and await pg.evaluate("S.lit.length + S.seen.length") == 0, "lab starts empty")
    check(await pg.inner_text("#cgo") == "LOOK" or (await pg.inner_text("#cgo")).lower() == "look", "observatory says the case is not open yet")
    await pg.click("nav.tabs button[data-view=case]")
    check(await pg.locator("#glass .lockscr").count() == 1, "case workstation is locked at the start")
    check(await pg.locator("#casel .need").count() == 2, "locked case lists the two School steps it needs")
    check(await pg.evaluate("[...document.querySelectorAll('.appsw button')].every(b => b.disabled)"), "PowerShell and Edge cannot be opened while locked")
    await pg.click("#casel .need [data-gg=workloads]")
    check(await pg.evaluate("cur === 'school' && school.g === 'workloads' && school.l === 0"), "Open step jumps to School step 5")
    await pg.evaluate("school.g='graph';school.l=1;school.qa=null;renderStrip();renderLesson()")
    await pg.reload()
    await pg.wait_for_timeout(400)
    check(await pg.evaluate("school.g === 'graph' && school.l === 1"), "School position remembered after reload")
    check(await pg.evaluate("!!localStorage.getItem('vigil.v1') && !localStorage.getItem('vigil.demo.v1')"), "lab saves to vigil.v1 only")
    await pg.click("nav.tabs button[data-view=obs]")


async def replay_lab(pg):
    sl = await pg.evaluate("S.sl")
    await pg.reload()
    await pg.wait_for_timeout(400)
    check(await pg.evaluate("S.caseDone") and await pg.evaluate("S.sl") == sl, "solved case and starlight survive a reload")
    check((await pg.inner_text("#cgo")).lower() == "replay", "observatory offers a replay")
    await pg.click("#cgo")
    check(await pg.locator("#glass .lockscr").count() == 0 and await pg.evaluate("C.done.length") == 0, "replay opens a fresh case")
    await pg.evaluate("complete('find');complete('contain');complete('fix')")
    await pg.wait_for_timeout(1200)
    check(await pg.evaluate("S.sl") == sl, "replay gives no new starlight")
    gtxt = await pg.inner_text(".closed .gain")
    check("practice only" in gtxt.lower(), "replay close screen says practice only: " + gtxt)
    await pg.click("[data-closed]")


async def reduced(b):
    ctx = await b.new_context(viewport={"width": 1440, "height": 900}, reduced_motion="reduce")
    pg = await ctx.new_page()
    await pg.goto(DEMO_F)
    await pg.evaluate("localStorage.clear()")
    await pg.reload()
    await pg.wait_for_timeout(300)
    want = await pg.evaluate("Math.round(readiness().all*100)")
    check(await pg.evaluate("reduce") and (await pg.inner_text("#rdy")).startswith(str(want)), "reduced motion: readiness shows its value at once")
    check(await pg.text_content("#gt1") == str(round(await pg.evaluate("readiness().per[0].v") * 100)) + "%", "reduced motion: gauge needle placed at once")
    await pg.evaluate("S.read = LESSONS.tenant.map((_, i) => 'tenant' + i); school.g = 'tenant'; checkStep(); go('obs')")
    check(await pg.locator("#orrery .kc.draw").count() == 0, "reduced motion: no line drawing")
    await ctx.close()


async def suite(b, F, lab):
        tag = "lab" if lab else "demo"
        pg = await b.new_page(viewport={"width": 1440, "height": 900})
        errs = []
        pg.on("pageerror", lambda e: errs.append(str(e)))
        pg.on("console", lambda m: errs.append(m.text) if m.type == "error" else None)
        await pg.goto(F)
        await pg.evaluate("localStorage.clear()")
        await pg.reload()
        await pg.wait_for_timeout(600)
        if lab:
            await fresh_lab(pg)
        else:
            await pg.click("nav.tabs button[data-view=case]")
            check(await pg.locator("#glass .lockscr").count() == 0, "demo case is open for review")
            await pg.click("nav.tabs button[data-view=obs]")

        check(await pg.inner_text("#ecode") == "EXAM AB-650", "exam code visible in header")
        check("Administering Microsoft 365 and AI Services" in await pg.inner_text("#ename"), "exam name visible in header")
        check(await pg.locator("#orrery circle.star").count() == 58, "58 stars on the orrery")
        await pg.click("[data-skin=night]")
        check(await pg.get_attribute("#dome", "data-skin") == "night", "night chart switch")
        await pg.click("[data-skin=paper]")

        check(not await pg.evaluate("S.sound") and (await pg.inner_text("#sndb")).lower().endswith("off"), "sound is off by default")
        await pg.click("nav.tabs button[data-view=school]")
        ladder = await pg.evaluate("LADDER")
        check(len(ladder) == 11, "11 school steps")
        for g in ladder:
            n = await pg.evaluate(f"LESSONS['{g}'].length")
            for l in range(n):
                await pg.evaluate(f"school.g='{g}';school.l={l};school.qa=null;renderStrip();renderLesson()")
                facts = await pg.locator("#lesson .facts:not(.blk.watch .facts) li").count()
                check(await pg.locator("#lesson .blk:not(.watch) > .facts li").count() <= 3, f"{g} lesson {l + 1} has at most 3 facts")
                await pg.fill("#tyin", "zzz wrong")
                await pg.press("#tyin", "Enter")
                check("no" in (await pg.get_attribute("#tyin", "class") or ""), f"{g} lesson {l + 1} rejects a wrong typed answer")
                ans = await pg.evaluate(f"TYPED['{g}'][{l}].a[0]")
                await pg.fill("#tyin", ans.upper() + "  ")
                await pg.press("#tyin", "Enter")
                check("ok" in (await pg.get_attribute("#tyin", "class") or ""), f"{g} lesson {l + 1} accepts '{ans}'")
                await pg.click("[data-reveal]")
                a = await pg.evaluate("school.qa.a")
                await pg.click(f"#lesson [data-o='{a}']")
                rows = await pg.locator("#lesson .where tr").count()
                for r in range(rows):
                    await pg.locator("#lesson .where tr").nth(r).click()
                    check(await pg.evaluate("!!document.querySelector('#lens .it.on')"), f"{g} lesson {l + 1} row {r + 1} lights up in the Lens")
        check(await pg.evaluate("S.seen.length+S.lit.length") == 58, "finishing every lesson studies every star")
        check(await pg.evaluate("SND.log.length") == 0, "no sound plays while sound is off")
        check(await pg.locator("#lumen .lsay").count() == 1, "Lumen says something after the checks")
        check("finished" in (await pg.evaluate("S.kline || ''")), "Keeper remembers the finished step")
        await pg.click("nav.tabs button[data-view=obs]")
        check(await pg.locator("#orrery .kc.draw").count() > 0, "newly studied constellations draw their lines")
        await pg.wait_for_timeout(1000)
        check((await pg.inner_text("#rdy")).startswith(str(await pg.evaluate("Math.round(readiness().all*100)"))), "readiness counts up to its value")
        check(await pg.inner_text("#kmsg") == await pg.evaluate("S.kline"), "Keeper says the step line on the observatory")
        check(await pg.evaluate("LADDER.every(stepDone) || !stepDone(nextStep())"), "Tonight's watch points at an unfinished step")
        await pg.click("#sndb")
        check(await pg.evaluate("S.sound") and await pg.evaluate("SND.log.includes('tick')"), "sound toggle turns sound on")
        await pg.reload()
        await pg.wait_for_timeout(400)
        check(await pg.evaluate("S.sound") and (await pg.inner_text("#sndb")).lower().endswith("on"), "sound choice remembered after reload")
        check(await pg.evaluate("caseOpen()"), "case opens once steps 5 and 8 are finished")

        await pg.click("nav.tabs button[data-view=case]")
        await pg.evaluate("C.lag = 400")
        await pg.click("[data-app=copilot]")
        await pg.click("[data-cpq]")
        await pg.press("#cpin", "Enter")
        await pg.wait_for_timeout(150)
        check("wages ledger" in (await pg.inner_text("#cpmsgs")).lower(), "Copilot quotes the wages ledger before the fix")
        await pg.fill("#cpin", "what is the weather")
        await pg.press("#cpin", "Enter")
        await pg.wait_for_timeout(150)
        check("only answers the steward" in (await pg.inner_text("#cpmsgs")), "Copilot window says plainly it only simulates one question")
        await pg.click("[data-app=ps]")
        await ps(pg, "Get-SPOSite")
        check("No connection available" in " ".join(await last_lines(pg, 3)), "SPO cmdlet refused before connecting")
        await ps(pg, "Connect-SPOService -Url https://halcyon.sharepoint.com")
        check("Could not connect" in " ".join(await last_lines(pg, 3)), "connect refused without -admin")
        await ps(pg, "Connect-SPOService -Url https://halcyon-admin.sharepoint.com")
        await ps(pg, "Get-SPOSite Treasury")
        check("Invalid URI" in " ".join(await last_lines(pg, 3)), "site name instead of URL refused")
        await ps(pg, "Set-SPOSite -Identity https://halcyon.sharepoint.com/sites/treasury -RestrictContentOrgWideSearch true")
        check("Boolean parameters accept only" in " ".join(await last_lines(pg, 2)), "bare true refused for a Boolean")
        await ps(pg, "Set-SPOSite -Identity https://halcyon.sharepoint.com/sites/treasury -Rest $true")
        check("ambiguous" in " ".join(await last_lines(pg, 2)), "ambiguous short parameter refused")
        check(not await pg.evaluate("C.rcd"), "nothing changed after refused commands")
        await ps(pg, "Set-SPOSite -Identity https://halcyon.sharepoint.com/sites/treasury -RestrictContentOrgWideSearch $true")
        check(await pg.evaluate("C.rcd && C.done.includes('contain')"), "correct PowerShell completes the contain goal")
        await pg.click("[data-app=copilot]")
        await pg.fill("#cpin", "summarise last month's supply costs")
        await pg.press("#cpin", "Enter")
        await pg.wait_for_timeout(100)
        check("wages" in (await pg.inner_text("#cpmsgs .m.ai >> nth=-1")).lower(), "right after the change Copilot still finds the ledger (index not caught up)")
        await pg.wait_for_timeout(700)
        await pg.fill("#cpin", "Summarise last month's supply costs")
        await pg.press("#cpin", "Enter")
        await pg.wait_for_timeout(100)
        check("wages" not in (await pg.inner_text("#cpmsgs .m.ai >> nth=-1")).lower(), "after the index catches up Copilot no longer quotes the ledger")
        check(await pg.evaluate("C.log.some(e => e.kind === 'say' && e.t.startsWith('Quillon Ashgrove:'))") and await pg.locator('#casel .e.say b').count() >= 1, "Quillon replies in the ledger after the fix, as a character line")
        await pg.click("[data-app=ps]")
        await ps(pg, "Get-SPOSite -Identity https://halcyon.sharepoint.com/sites/treasury | Select RestrictContentOrgWideSearch")
        check("True" in " ".join(await last_lines(pg, 3)), "Select shows True with a capital")

        await pg.click("[data-app=browser]")
        await pg.click("#glass [data-pl]")
        await pg.click("[data-pj=spo]")
        await pg.click("#glass [data-pn='spo|active']")
        await pg.type("#psearch", "trea")
        check(await pg.input_value("#psearch") == "trea" and await pg.locator("#glass tr[data-site]").count() == 1, "typed site search filters and keeps focus")
        await pg.fill("#psearch", "")
        await pg.click("#glass tr[data-site=treasury]")
        await pg.click("#glass [data-ct=settings]")
        check("Restrict content from Microsoft Copilot" in await pg.inner_text("#glass .panel"), "site setting uses the real toggle name")
        await pg.click("[data-ca=saveSite]")
        check("Saving..." in await pg.inner_text("#glass .panel"), "Save shows Saving...")
        await pg.wait_for_timeout(900)
        check("Changes saved" in await pg.inner_text("#glass .panel"), "then a Changes saved bar")
        await pg.click("[data-ca=closePanel]")
        await pg.click("#glass [data-pn='spo|dag']")
        await pg.click("[data-ca=openReport]")
        await pg.click("[data-rep=treasury]")
        await pg.click("[data-ca=review]")
        await pg.click("[data-ca=sendReview]")
        await pg.wait_for_timeout(4300)
        check(await pg.evaluate("C.done.length") == 3, "case completes")
        check(await pg.locator(".closed").count() == 1, "case closed screen shows")

        await pg.click("[data-closed]")
        if lab:
            await replay_lab(pg)
        await pg.click("nav.tabs button[data-view=trial]")
        await pg.click("[data-exam=start]")
        check("AB-650" in await pg.inner_text("#exam"), "exam code on the trial screen")
        check("demo" not in (await pg.inner_text("#exam")).lower(), "trial screen never says demo")
        m0 = await pg.evaluate("S.miss.filter(m => m.kind === 'trial').length")
        await pg.click("[data-exam=next]")
        await pg.click("[data-exam=next]")
        await pg.click("[data-exam=next]")
        await pg.click("[data-exam=next]")
        await pg.click("[data-exam=finish]")
        check(await pg.evaluate("S.miss.filter(m => m.kind === 'trial').length") == m0 + 5, "unanswered trial questions go to the oopsies")
        check(not errs, "no console or page errors: " + "; ".join(errs[:3]))
        await pg.close()


async def main():
    registry()
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path="/usr/bin/google-chrome", args=["--no-sandbox"])
        await reduced(b)
        for F, lab in [(DEMO_F, False), (LAB_F, True)]:
            before = len(FAIL)
            await suite(b, F, lab)
            print(("lab" if lab else "demo"), "ok" if len(FAIL) == before else "FAILED")
        for w, h in [(1280, 766), (1280, 800), (1440, 866), (1440, 900), (1920, 1046), (1920, 1080)]:
            pg = await b.new_page(viewport={"width": w, "height": h})
            await pg.goto(LAB_F)
            await pg.evaluate("localStorage.clear()")
            await pg.reload()
            await pg.wait_for_timeout(300)
            sh, ch = await pg.evaluate("(() => { const s = document.querySelector('.side'); return [s.scrollHeight, s.clientHeight]; })()")
            check(sh <= ch, f"observatory side column fits at {w}x{h} ({sh} > {ch})")
            hd = await pg.evaluate("(() => { const c = document.querySelector('.examchip').getBoundingClientRect(); return c.top >= 0 && c.bottom <= 58 && c.right <= innerWidth - 8; })()")
            check(hd, f"exam chip stays inside the header at {w}x{h}")
            await pg.close()
        await b.close()


asyncio.run(main())
print("ALL OK" if not FAIL else f"{len(FAIL)} FAILED")
sys.exit(1 if FAIL else 0)
