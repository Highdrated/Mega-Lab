    await pg.evaluate("SHIFT = 45; go('tonight')")
    check(await pg.evaluate("streakOf().n") == 0, "a missed night breaks the streak")
    check("missed a night" in await pg.inner_text("#wkl"), "Keeper explains the broken streak")
    check(await pg.evaluate("[S.sl, S.lit.length, S.seen.length, S.read.length, S.unlocks.join()]") == keep, "a missed night deletes no progress and no reward")
    check(await pg.evaluate("streakOf().best") == 3, "best streak is kept")
    await pg.reload()
    await pg.wait_for_timeout(300)
    check(await pg.evaluate("S.nights.length === 3 && S.unlocks.includes('vellum') && !!S.watch"), "streak, rewards and watch survive a reload")
    for n in range(4, 8):
        await pg.evaluate(f"SHIFT = {41 + n}; S.watch = null; ensureWatch(); S.watch.items.forEach(it => {{ if (it.k === 'oops') S.watch.done.push(it.id); if (it.k === 'lesson') S.read.push(it.g + it.l); if (it.k === 'trial') S.watch.trial = true; }}); watchCheck()")
