async def recall_both(pg):
    k = await pg.evaluate("school.rc && school.rc.k")
    if not k:
        return
    q = await pg.evaluate("TYPED[revG(school.rc.k)][revL(school.rc.k)].q")
    check(q in await pg.inner_text("#lesson .blk.recall") and await pg.locator("#lesson .lbody.folded").count() == 1, f"recall of {k} comes first, with the new lesson folded")
    await pg.fill("#tyin", "zzz wrong")
    await pg.press("#tyin", "Enter")
    check("no" in (await pg.get_attribute("#tyin", "class") or "") and await pg.evaluate(f"pendList().includes('{k}') && !S.read.includes('{k}')"), f"{k} recall rejects a wrong answer and stays waiting")
    await pg.evaluate("school.qa = null; renderLesson()")
    check(await pg.evaluate(f"school.rc && school.rc.k === '{k}'"), f"{k} recall is asked again when the page opens again")
    ans = await pg.evaluate(f"TYPED[revG('{k}')][revL('{k}')].a[0]")
    await pg.fill("#tyin", ans.upper() + "  ")
    await pg.press("#tyin", "Enter")
    check("ok" in (await pg.get_attribute("#tyin", "class") or "") and await pg.evaluate(f"S.read.includes('{k}')"), f"{k} recall accepts '{ans}' and finishes that lesson")


