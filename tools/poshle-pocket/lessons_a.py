def _rot(ch, key):
    n = len(ch)
    k = len(key) % n
    r = ch[k:] + ch[:k]
    return r, (n - k) % n


def P(code, ch, why):
    r, a = _rot(ch, code)
    return {"t": "predict", "code": code, "choices": r, "a": a, "why": why}


def K(ask, ch, why):
    r, a = _rot(ch, ask)
    return {"t": "pick", "ask": ask, "choices": r, "a": a, "why": why}


def F(code, target, ch, ok, why):
    return {"t": "fill", "code": code, "target": target, "choices": ch, "ok": ok, "why": why}


def B(ask, setup, target, tiles, sol, ok, why):
    return {"t": "build", "ask": ask, "setup": setup, "target": target, "tiles": tiles, "sol": sol, "ok": ok, "why": why}


def O(lines, target, sol, ok, why):
    return {"t": "order", "lines": lines, "target": target, "sol": sol, "ok": ok, "why": why}


def G(lines, bad, fix, expect, got, why):
    return {"t": "bug", "lines": lines, "bad": bad, "fix": fix, "expect": expect, "got": got, "why": why}


def C(h, body, code=None, out=None, flow=None, check=None):
    c = {"h": h, "body": body}
    if code is not None:
        c["code"] = code
        c["out"] = out
    if flow:
        c["flow"] = flow
    if check:
        c["check"] = check
    return c


