def _perms(xs):
    if len(xs) <= 1:
        return [list(xs)]
    out = []
    for i in range(len(xs)):
        for p in _perms(xs[:i] + xs[i + 1:]):
            out.append([xs[i]] + p)
    return out


def _ok(head, rest, tail=()):
    return [",".join(str(x) for x in list(head) + p + list(tail)) for p in _perms(list(rest))]


