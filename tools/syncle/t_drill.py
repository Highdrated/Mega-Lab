import asyncio, os, sys
from playwright.async_api import async_playwright
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
LAB = "file://" + os.path.join(ROOT, "labs", "syncle.html")
HOME = "file://" + os.path.join(ROOT, "index.html")
FAIL = []
def check(ok, msg):
    print(("ok   " if ok else "FAIL ") + msg)
    if not ok: FAIL.append(msg)

async def fresh(b, w=1440, h=900, hash="", pre=None):
    pg = await b.new_page(viewport={"width": w, "height": h})
    errs = []
    pg.on("pageerror", lambda e: errs.append(str(e)))
    await pg.add_init_script("try{sessionStorage.setItem('syncle-splash','1')}catch(e){}")
    await pg.goto(LAB)
    await pg.evaluate("localStorage.clear()")
    if pre: await pg.evaluate(pre)
    await pg.goto(LAB + hash)
    await pg.wait_for_timeout(300)
    return pg, errs

async def type_line(pg, text):
    await pg.click("#drLine")
    await pg.keyboard.type(text, delay=2)
    await pg.wait_for_timeout(350)

async def flow(b):
    pg, errs = await fresh(b)
    await pg.click("#drillbtn")
    check(await pg.locator("#drill:not(.hide) .dmodes").count() == 1, "the DRILL button opens the drill lobby")
    n = await pg.evaluate("drBank().length")
    check(n >= 70, f"the bank holds {n} real commands")
    check(await pg.evaluate("drBank().every(c => !/kaatje/i.test(c.cmd + c.q))"), "no real name in any drill command")
    await pg.click("#drFlow")
    c = await pg.evaluate("DRL.q[0].cmd")
    check(await pg.evaluate("DRL.q.length") == 4 and await pg.locator(".dpills span.on").inner_text() == "GHOST", "Flow starts with four commands, the first over the ghost")
    await pg.click("#drLine")
    await pg.keyboard.type(c[:3] + "#", delay=2)
    check(await pg.locator(".dtxt .dx").count() == 1 and await pg.evaluate("DRL.err") == 1, "a wrong character shows red and counts as a slip")
    await pg.keyboard.press("Backspace")
    await pg.keyboard.type(c[3:], delay=2)
    await pg.wait_for_timeout(350)
    check(await pg.locator(".dpills span.on").inner_text() == "GHOST", "a line with a slip is typed over the ghost once more")
    await pg.keyboard.press("Tab")
    check("No Tab" in await pg.inner_text(".dmsg"), "Tab is refused with a reason")
    await type_line(pg, c)
    check(await pg.locator(".dpills span.on").inner_text() == "FADE", "a clean line moves on to the faded ghost")
    check(await pg.locator(".dtxt .dh").count() > 0, "the faded ghost hides most characters")
    await type_line(pg, c)
    check(await pg.locator(".dpills span.on").inner_text() == "BLANK" and await pg.locator(".dtxt").count() == 0, "then a blank prompt with no ghost")
    await pg.fill("#drIn", c)
    await pg.press("#drIn", "Enter")
    check("from memory" in (await pg.inner_text(".dmsg")).lower(), "the right command from memory is accepted")
    await pg.wait_for_timeout(1100)
    check(await pg.evaluate("DRL.qi") == 1, "the round moves to the second command")
    c2 = await pg.evaluate("DRL.q[1].cmd")
    await type_line(pg, c2)
    await type_line(pg, c2)
    await pg.fill("#drIn", "Get-Nothing")
    await pg.press("#drIn", "Enter")
    check("One more try" in await pg.inner_text(".dmsg"), "a wrong blank answer gets one more try")
    await pg.fill("#drIn", "Get-Nothing -Again")
    await pg.press("#drIn", "Enter")
    check(c2 in await pg.inner_text(".dmsg") and await pg.locator("#drOn").count() == 1, "after two misses the command is shown")
    await pg.click("#drOn")
    for i in [2, 3]:
        ci = await pg.evaluate(f"DRL.q[{i}].cmd")
        await type_line(pg, ci)
        await type_line(pg, ci)
        await pg.fill("#drIn", ci)
        await pg.press("#drIn", "Enter")
        await pg.wait_for_timeout(1100)
    check(await pg.locator(".dsum").count() == 1 and "3 of 4" in await pg.inner_text(".dsum"), "the round summary counts the first-try answers")
    st = await pg.evaluate("[drPeek(DRL.res[0].c.id), drPeek(DRL.res[1].c.id)]")
    check(st[0]["lv"] == 3 and st[0]["due"] > 0 and st[1]["lv"] == 1 and st[1]["miss"] == 1, "a clean card is spaced out, a missed card stays due")
    check(await pg.evaluate("S.credits") >= 9, "fragments are paid for the clean answers")
    check("Sequence" in await pg.inner_text(".dres") or await pg.locator(".dres > div").count() == 4, "the summary lists the four commands")
    await pg.keyboard.press("Enter")
    check(await pg.evaluate("DRL.mode === 'flow' && DRL.qi === 0 && DRL.res.length === 1"), "Enter starts another round")
    q0 = await pg.evaluate("DRL.q.map(c => c.id)")
    missed = await pg.evaluate("Object.entries(S.drl.cards).filter(([k, v]) => v.miss).map(([k]) => k)")
    check(all(m in q0 for m in missed), "the missed command comes back in the next round")
    ok = await pg.evaluate("""(() => {
      const c = drBank().find(x => /^Update-MgUser -UserId \\S+ -JobTitle "[^"]+"$/.test(x.cmd));
      if (!c) return 'none';
      const m = c.cmd.match(/^Update-MgUser -UserId (\\S+) -JobTitle ("[^"]+")$/);
      return [drBlankOK(c, c.cmd), drBlankOK(c, 'Update-MgUser -JobTitle ' + m[2] + ' -UserId ' + m[1]), drBlankOK(c, "update-mguser -userid " + m[1] + " -jobtitle '" + m[2].slice(1, -1) + "'"), drBlankOK(c, 'Update-MgUser -UserId ' + m[1] + ' -JobTitle "Wrong"')].join();
    })()""")
    check(ok == "true,true,true,false", f"blank answers run in the engine: any order and quote style PowerShell accepts, wrong values refused ({ok})")
    check(not errs, "no page errors in Flow " + "; ".join(errs)[:200])
    await pg.close()

async def vigil_feed(b):
    pre = "localStorage.setItem('vigil.v1', JSON.stringify({ miss: [{ id: 'ps:lock1', kind: 'ps', ref: { e: 'lock' }, t: 'x' }] }))"
    pg, errs = await fresh(b, pre=pre)
    check(await pg.inner_text("#drillDue") == "1", "the DRILL button shows one due from Vigil")
    await pg.click("#drillbtn")
    check("1" in await pg.inner_text(".dstats > div:nth-child(4) b"), "the lobby counts one Vigil mistake")
    await pg.click("#drFlow")
    check(await pg.evaluate("DRL.q[0].id") == "spo:3" and "FROM VIGIL" in await pg.inner_text(".dsrc"), "the Vigil mistake comes first, marked")
    c = await pg.evaluate("DRL.q[0].cmd")
    await type_line(pg, c)
    await type_line(pg, c)
    await pg.fill("#drIn", c)
    await pg.press("#drIn", "Enter")
    await pg.wait_for_timeout(1100)
    check(await pg.evaluate("S.drl.vigDone.includes('ps:lock1') && drVigil().length === 0"), "a clean answer clears the Vigil mistake")
    check(not errs, "no page errors in the Vigil feed")
    await pg.close()

async def rush(b):
    pg, errs = await fresh(b)
    await pg.click("#drillbtn")
    await pg.click("#drRush")
    check(await pg.locator(".dlives i.on").count() == 3 and await pg.locator("#drFuse").count() == 1, "Rush starts with three lives and a fuse")
    await pg.wait_for_timeout(400)
    w = await pg.evaluate("parseFloat(document.querySelector('#drFuse').style.width)")
    check(0 < w < 100, f"the fuse burns down ({w:.0f}%)")
    c = await pg.evaluate("DRL.rush.card.cmd")
    await type_line(pg, c)
    check(await pg.evaluate("DRL.rush.score") > 0 and await pg.evaluate("DRL.rush.combo") == 1, "a clean line scores and builds the combo")
    check(await pg.evaluate("DRL.rush.done") == 1, "the run counts the command")
    await pg.evaluate("DRL.rush.fuse = 30")
    await pg.wait_for_timeout(400)
    check(await pg.evaluate("DRL.rush.lives") == 2 and "Out of time" in await pg.inner_text(".dmsg"), "a burnt fuse costs a life and shows the command")
    await pg.wait_for_timeout(1800)
    await pg.evaluate("DRL.rush.done = 5")
    c = await pg.evaluate("DRL.rush.card.cmd")
    await type_line(pg, c)
    await pg.wait_for_timeout(300)
    check(await pg.evaluate("DRL.rush.lvl") == 2, "every six commands is a level up")
    await pg.evaluate("DRL.rush.lvl = 5; drRushNext()")
    check(await pg.locator(".dtxt .dg").count() == 0 and await pg.locator(".dtxt .dh").count() == 0, "from level 5 there is no ghost")
    await pg.click("#drQuit")
    check(await pg.locator(".dsum").count() == 1 and await pg.evaluate("S.drl.best") > 0 and await pg.evaluate("S.drl.runs.length") == 1, "ending the run saves the score and the best")
    check(await pg.evaluate("DRL.raf") == 0, "the fuse loop stops after the run")
    await pg.click("#drBack")
    check(await pg.locator(".druns div").count() == 1, "the lobby lists the run")
    await pg.click("#home")
    check(await pg.locator("#drill.hide").count() == 1 and await pg.locator("#corridor:not(.hide)").count() == 1, "the logo leaves the drill for the corridor")
    check(not errs, "no page errors in Rush " + "; ".join(errs)[:200])
    await pg.close()

async def hash_and_launcher(b):
    pg, errs = await fresh(b, hash="#drill")
    check(await pg.locator("#drill:not(.hide)").count() == 1, "syncle.html#drill opens the drill")
    await pg.close()
    pg = await b.new_page(viewport={"width": 1440, "height": 900})
    await pg.goto(HOME)
    await pg.evaluate("localStorage.clear(); localStorage.setItem('vigil.v1', JSON.stringify({ miss: [{ id: 'ps:a', kind: 'ps', ref: { e: 'set' } }] }))")
    await pg.reload()
    await pg.wait_for_timeout(500)
    items = await pg.evaluate("todayItems().filter(i => i.lab === 'syncle').map(i => i.text + '|' + i.hash)")
    check(items == ["Drill your Vigil PowerShell mistakes|drill"], f"the launcher reminds about the Vigil mistakes ({items})")
    await pg.evaluate("localStorage.setItem('syncle.v1', JSON.stringify({ drl: { cards: { 'connect:0': { lv: 3, due: 1, n: 1 }, 'connect:1': { lv: 3, due: 9e15, n: 1 } }, vigDone: ['ps:a'] } }))")
    items = await pg.evaluate("todayItems().filter(i => i.lab === 'syncle').map(i => i.text)")
    check(items == ["1 command to drill"], f"the launcher counts due drill commands ({items})")
    await pg.close()

async def layout(b):
    for w, h in [(1280, 800), (1440, 900), (1920, 1080), (390, 844)]:
        pg, errs = await fresh(b, w, h)
        await pg.click("#drillbtn")
        fit = "(() => { const d = document.querySelector('#drill'); return [...d.querySelectorAll('.dwrap *')].every(e => { const r = e.getBoundingClientRect(); return r.right <= window.innerWidth + 1; }) && d.scrollWidth <= d.clientWidth + 1; })()"
        check(await pg.evaluate(fit), f"the lobby fits at {w}x{h}")
        await pg.click("#drFlow")
        check(await pg.evaluate(fit), f"Flow fits at {w}x{h}")
        await pg.click("#drQuit")
        await pg.click("#drRush")
        check(await pg.evaluate(fit), f"Rush fits at {w}x{h}")
        await pg.screenshot(path=f"/tmp/shots/drill-rush-{w}.png")
        await pg.click("#drQuit")
        await pg.close()

async def main():
    os.makedirs("/tmp/shots", exist_ok=True)
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path="/usr/bin/google-chrome", args=["--no-sandbox"])
        for fn in [flow, vigil_feed, rush, hash_and_launcher, layout]:
            try:
                await fn(b)
            except Exception as e:
                check(False, f"{fn.__name__} crashed: {e!r}"[:400])
        await b.close()
    print("ALL OK" if not FAIL else f"{len(FAIL)} FAILED")
    sys.exit(1 if FAIL else 0)

asyncio.run(main())
